-- Reference schema already applied to the hosted Supabase project.
-- Anonymous clients can read published catalog entries. Only users listed in
-- video_admins can manage records or read unpublished entries.

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 200),
  video_url text not null check (char_length(trim(video_url)) > 0),
  thumbnail_url text not null check (char_length(trim(thumbnail_url)) > 0),
  description text not null default '',
  category text not null default 'Videos',
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.video_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.videos enable row level security;
alter table public.video_admins enable row level security;
grant select on public.videos to anon, authenticated;
grant usage, select on sequence public.videos_id_seq to anon, authenticated;
grant select on public.video_admins to authenticated;
grant insert, update, delete on public.videos to authenticated;

drop policy if exists "Admins can read own admin flag" on public.video_admins;
create policy "Admins can read own admin flag" on public.video_admins
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Published videos are readable publicly" on public.videos;
create policy "Published videos are readable publicly" on public.videos
  for select to anon, authenticated using (
    is_published = true or exists (
      select 1 from public.video_admins a where a.user_id = (select auth.uid())
    )
  );
drop policy if exists "Admins can insert videos" on public.videos;
create policy "Admins can insert videos" on public.videos
  for insert to authenticated with check (
    exists (select 1 from public.video_admins a where a.user_id = (select auth.uid()))
  );
drop policy if exists "Admins can update videos" on public.videos;
create policy "Admins can update videos" on public.videos
  for update to authenticated using (
    exists (select 1 from public.video_admins a where a.user_id = (select auth.uid()))
  ) with check (
    exists (select 1 from public.video_admins a where a.user_id = (select auth.uid()))
  );
drop policy if exists "Admins can delete videos" on public.videos;
create policy "Admins can delete videos" on public.videos
  for delete to authenticated using (
    exists (select 1 from public.video_admins a where a.user_id = (select auth.uid()))
  );
